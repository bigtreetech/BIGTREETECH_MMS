import argparse
import os
from pathlib import Path
import re
import shutil
import tempfile

SUPPORTED_SLICERS = ('PrusaSlicer', 'SuperSlicer', 'OrcaSlicer', 'BambuStudio')
MMS_FINGERPRINT = "; processed by MMS"
SLICER_REGEX = re.compile(
    r"^;.*generated by\s+(\w+)|^;\s*(BambuStudio)\b", re.IGNORECASE
)
TOOL_DISCOVERY_REGEX = r"^\s*(?:MMS_CHANGE_TOOL\b.*?\bTOOL=|T)(?P<tool>\d+)(?=\s|;|$)"

METADATA_TOOL_DISCOVERY = "!referenced_tools!"
METADATA_TOTAL_TOOLCHANGES = "!total_toolchanges!"

# PS/SS uses "extruder_colour", Orca uses "filament_colour"
COLORS_REGEX = {
    'PrusaSlicer' : r"^;\s*(?:extruder|filament)_colour\s*=\s*(#.*;*.*)$",
    'SuperSlicer' : r"^;\s*extruder_colour\s*=\s*(#.*;*.*)$",
    'OrcaSlicer'  : r"^;\s*filament_colour\s*=\s*(#.*;*.*)$",
    'BambuStudio' : r"^;\s*filament_colour\s*=\s*(#.*;*.*)$",
}
METADATA_COLORS = "!colors!"

TEMPS_REGEX = r"^;\s*(nozzle_)?temperature\s*=\s*(.*)$"
METADATA_TEMPS = "!temperatures!"

MATERIALS_REGEX = r"^;\s*filament_type\s*=\s*(.*)$"
METADATA_MATERIALS = "!materials!"

PURGE_VOLUMES_REGEX = r"^;\s*(flush_volumes_matrix|wiping_volumes_matrix)\s*=\s*(.*)$"
METADATA_PURGE_VOLUMES = "!purge_volumes!"

FILAMENT_NAMES_REGEX = r"^;\s*(filament_settings_id)\s*=\s*(.*)$"
METADATA_FILAMENT_NAMES = "!filament_names!"

# Detection for next pos processing
T_PATTERN  = re.compile(r'^\s*T(\d+)\s*(?:;.*)?$', re.IGNORECASE)
G1_PATTERN = re.compile(
    r'^\s*G[01](?=\s|$)(?=[^;]*\sX(-?[\d.]+))(?=[^;]*\sY(-?[\d.]+))',
    re.IGNORECASE
)

def gcode_processed_already(file_path):
    with open(file_path, encoding="utf-8", errors="surrogateescape") as in_file:
        return in_file.readline().strip().casefold() == MMS_FINGERPRINT.casefold()


def parse_gcode_file(file_path):
    has_placeholders = False
    found_fields = set()
    slicer = None

    tools_used = set()
    total_toolchanges = 0
    colors = []
    temps = []
    materials = []
    purge_volumes = []
    filament_names = []

    with open(file_path, encoding="utf-8", errors="surrogateescape") as in_file:
        for line in in_file:
            match = SLICER_REGEX.match(line)
            if not match:
                continue
            name = (match.group(1) or match.group(2)).casefold()
            slicer = next((item for item in SUPPORTED_SLICERS
                           if item.casefold() == name), None)
            if slicer is not None:
                break

    if slicer is not None:
        tools_regex = re.compile(TOOL_DISCOVERY_REGEX, re.IGNORECASE)
        colors_regex = re.compile(COLORS_REGEX[slicer], re.IGNORECASE)
        temps_regex = re.compile(TEMPS_REGEX, re.IGNORECASE)
        materials_regex = re.compile(MATERIALS_REGEX, re.IGNORECASE)
        purge_volumes_regex = re.compile(PURGE_VOLUMES_REGEX, re.IGNORECASE)
        filament_names_regex = re.compile(FILAMENT_NAMES_REGEX, re.IGNORECASE)

        with open(file_path, encoding="utf-8", errors="surrogateescape") as in_file:
            for line in in_file:
                if METADATA_TOOL_DISCOVERY in line or METADATA_TOTAL_TOOLCHANGES in line or \
                   METADATA_COLORS in line or METADATA_TEMPS in line or \
                   METADATA_MATERIALS in line or METADATA_PURGE_VOLUMES in line or \
                   METADATA_FILAMENT_NAMES in line:
                    has_placeholders = True

                match = tools_regex.match(line)
                if match:
                    tool = match.group("tool")
                    tools_used.add(int(tool))
                    total_toolchanges += 1

                if 'colors' not in found_fields:
                    match = colors_regex.match(line)
                    if match:
                        colors = [color.strip().lstrip('#') for color in match.group(1).split(';')]
                        found_fields.add('colors')

                if 'temps' not in found_fields:
                    match = temps_regex.match(line)
                    if match:
                        temps = re.split(';|,', match.group(2).strip())
                        found_fields.add('temps')

                if 'materials' not in found_fields:
                    match = materials_regex.match(line)
                    if match:
                        materials = match.group(1).strip().split(';')
                        found_fields.add('materials')

                if 'purge_volumes' not in found_fields:
                    match = purge_volumes_regex.match(line)
                    if match:
                        purge_volumes = [v.strip() for v in match.group(2).strip().split(',')]
                        found_fields.add('purge_volumes')

                if 'filament_names' not in found_fields:
                    match = filament_names_regex.match(line)
                    if match:
                        filament_names = [e.strip() for e in re.split(',|;', match.group(2).strip())]
                        found_fields.add('filament_names')

    return (has_placeholders, sorted(tools_used), total_toolchanges, colors, temps, materials, purge_volumes, filament_names)

def process_file(input_filename, output_filename, insert_nextpos, replace_placeholders,
                 tools_used, total_toolchanges, colors, temps, materials, purge_volumes,
                 filament_names):
    with open(input_filename, encoding="utf-8", errors="surrogateescape") as infile, \
         open(output_filename, "w", encoding="utf-8", errors="surrogateescape") as outfile:
        buffer = []
        tool = None
        outfile.write(f"{MMS_FINGERPRINT}\n")

        def emit_tool(next_xy=None):
            pos = f' NEXT_POS="{next_xy[0]},{next_xy[1]}"' if next_xy else ""
            outfile.write(f"MMS_CHANGE_TOOL TOOL={tool}{pos} ; T{tool}\n")
            outfile.writelines(buffer)
            buffer.clear()

        for line in infile:
            if replace_placeholders:
                line = add_placeholder(line, tools_used, total_toolchanges, colors, temps,
                                       materials, purge_volumes, filament_names)
            t_match = T_PATTERN.match(line)
            if t_match:
                # A second Tx ends the previous tool's lookahead. Keep both.
                if tool is not None:
                    emit_tool()
                tool = t_match.group(1)
                if not insert_nextpos:
                    emit_tool()
                    tool = None
            elif tool is None:
                outfile.write(line)
            else:
                buffer.append(line)
                g1_match = G1_PATTERN.match(line)
                if g1_match:
                    emit_tool(g1_match.groups())
                    tool = None

        if tool is not None:
            emit_tool()

        outfile.write("\n; referenced_tools = %s\n" % ",".join(map(str, tools_used)))

def add_placeholder(line, tools_used, total_toolchanges, colors, temps, materials, purge_volumes, filament_names):
    if not line.startswith(";"):
        if METADATA_TOOL_DISCOVERY in line:
            line = line.replace(METADATA_TOOL_DISCOVERY, ",".join(map(str, tools_used)) if tools_used else "0")
        if METADATA_TOTAL_TOOLCHANGES in line:
            line = line.replace(METADATA_TOTAL_TOOLCHANGES, str(total_toolchanges))
        if METADATA_COLORS in line:
            line = line.replace(METADATA_COLORS, ",".join(map(str, colors)))
        if METADATA_TEMPS in line:
            line = line.replace(METADATA_TEMPS, ",".join(map(str, temps)))
        if METADATA_MATERIALS in line:
            line = line.replace(METADATA_MATERIALS, ",".join(map(str, materials)))
        if METADATA_PURGE_VOLUMES in line:
            line = line.replace(METADATA_PURGE_VOLUMES, ",".join(map(str, purge_volumes)))
        if METADATA_FILAMENT_NAMES in line:
            line = line.replace(METADATA_FILAMENT_NAMES, ",".join(map(str, filament_names)))
    return line

def main():
    parser = argparse.ArgumentParser(description="MMS G-Code Preprocessor")
    parser.add_argument("-f", "--filename", required=True, help="G-code file to parse")
    parser.add_argument("-p", "--path", help="Path for file")
    parser.add_argument("-m", "--placeholders", action='store_true', help="Process MMS placeholders")
    parser.add_argument("-n", "--nextpos", action='store_true', help="Add next position to tool change")
    args = parser.parse_args()

    file_path = (Path(args.path or "") / args.filename).resolve()
    if not file_path.is_file():
        parser.error(f"File not found: {file_path}")
    if gcode_processed_already(file_path):
        return

    has_placeholders, *metadata = parse_gcode_file(file_path)
    if not args.nextpos and not (args.placeholders and has_placeholders):
        return

    # Build next to the file, so success is a same-filesystem atomic replacement.
    fd, tmp_path = tempfile.mkstemp(dir=file_path.parent, prefix=".mms-")
    os.close(fd)
    try:
        process_file(file_path, tmp_path, args.nextpos, args.placeholders, *metadata)
        shutil.copymode(file_path, tmp_path)
        os.replace(tmp_path, file_path)
    finally:
        if os.path.exists(tmp_path):
            os.unlink(tmp_path)


if __name__ == "__main__":
    main()
